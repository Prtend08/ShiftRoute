"""Generate LaTeX result prose from hashed aggregate artifacts.

The script is intentionally deterministic. It refuses incomplete dataset
labels requested through ``--require-dataset`` and records every source hash,
so manuscript numbers never need to be copied by hand.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--aggregate-dir", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--calibration-audit-root", type=Path)
    parser.add_argument(
        "--cluster-aware-primary",
        type=Path,
        help="Primary comparisons generated by cluster_aware_inference.py",
    )
    parser.add_argument("--require-dataset", action="append", default=[])
    parser.add_argument("--backbone-count", type=int, required=True)
    return parser.parse_args()


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def latex_escape(value: object) -> str:
    text = str(value)
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(replacements.get(character, character) for character in text)


def format_pp(value: float) -> str:
    return f"{value * 100:+.3f}"


def format_probability(value: float) -> str:
    return f"{value * 100:.2f}\\%"


def format_p_latex(value: float) -> str:
    """Format a p-value without emitting an un-typeset ``e-05`` token."""

    if not np.isfinite(value):
        return r"\mathrm{NA}"
    if value == 0.0:
        return r"<10^{-300}"
    if value < 1e-3:
        exponent = int(np.floor(np.log10(value)))
        coefficient = value / (10.0**exponent)
        return rf"{coefficient:.2f}\times10^{{{exponent}}}"
    return f"{value:.3f}".lstrip("0")


def dataset_family(label: str) -> str:
    """Collapse raw/backbone-specific suites to the underlying benchmark."""

    compact = label.lower().replace("_", "-")
    if compact.startswith("cifar10-c"):
        return "CIFAR10-C"
    if compact.startswith("cifar100-c"):
        return "CIFAR100-C"
    if compact.startswith("imagenet100"):
        return "ImageNet100"
    if compact.startswith("imagenetv2"):
        return "ImageNetV2"
    if compact.startswith("imagenet-c"):
        return "ImageNet-C"
    return label


def method_for_dataset(frame: pd.DataFrame, dataset: str) -> str:
    methods = set(frame.loc[frame.dataset == dataset, "method"].astype(str))
    for candidate in ("shiftroute", "shiftroute_tent"):
        if candidate in methods:
            return candidate
    raise ValueError(f"no routed method in dataset {dataset}: {sorted(methods)}")


def join_clauses(clauses: list[str]) -> str:
    if not clauses:
        return "No completed dataset was available."
    if len(clauses) == 1:
        return clauses[0] + "."
    if len(clauses) == 2:
        return " and ".join(clauses) + "."
    return "; ".join(clauses[:-1]) + "; and " + clauses[-1] + "."


def main() -> None:
    args = parse_args()
    required_files = [
        "run_summary.csv",
        "paired_tests.csv",
        "route_audit.csv",
        "diagnostic_discrimination.csv",
        "clean_false_route_calibration.csv",
        "aggregation_manifest.json",
    ]
    paths = {name: args.aggregate_dir / name for name in required_files}
    missing = [str(path) for path in paths.values() if not path.exists()]
    if missing:
        raise FileNotFoundError(f"aggregate inputs missing: {missing}")
    run = pd.read_csv(paths["run_summary.csv"])
    tests = pd.read_csv(paths["paired_tests.csv"])
    route = pd.read_csv(paths["route_audit.csv"])
    diagnostic = pd.read_csv(paths["diagnostic_discrimination.csv"])
    calibration = pd.read_csv(paths["clean_false_route_calibration.csv"])
    datasets = sorted(run.dataset.astype(str).unique())
    missing_datasets = sorted(set(args.require_dataset) - set(datasets))
    if missing_datasets:
        raise RuntimeError(f"required datasets are incomplete: {missing_datasets}")
    condition_count = int(run[["dataset", "condition_id"]].drop_duplicates().shape[0])

    mean_clauses: list[str] = []
    worst_clauses: list[str] = []
    negative_transfer_clauses: list[str] = []
    diagnostic_clauses: list[str] = []
    routing_clauses: list[str] = []
    raw_tent_tradeoff_clauses: list[str] = []
    source_outcomes: list[tuple[float, float]] = []
    negative_transfer_outcomes: list[tuple[float, float]] = []
    mean_records: list[tuple[str, float, float]] = []
    worst_records: list[tuple[str, float]] = []
    negative_transfer_records: list[tuple[str, float, float, str]] = []
    diagnostic_records: list[tuple[str, float, float]] = []
    routing_records: list[tuple[str, float, float]] = []
    for dataset in datasets:
        routed_method = method_for_dataset(run, dataset)
        dataset_name = latex_escape(dataset)
        dataset_tests = tests[(tests.dataset == dataset) & (tests.method == routed_method)]
        mean_test = dataset_tests[
            (dataset_tests.metric == "mean_accuracy")
            & (dataset_tests.reference == "source")
            & (dataset_tests.comparison_family == "method_vs_source")
        ]
        worst_test = dataset_tests[
            (dataset_tests.metric == "worst_window_accuracy")
            & (dataset_tests.reference == "source")
            & (dataset_tests.comparison_family == "method_vs_source")
        ]
        if len(mean_test):
            row = mean_test.iloc[0]
            source_outcomes.append((float(row.mean_benefit), float(row.p_holm)))
            mean_records.append(
                (dataset, float(row.mean_benefit), float(row.p_holm))
            )
            mean_clauses.append(
                f"{dataset_name}: {format_pp(float(row.mean_benefit))} pp "
                f"(Holm $p={format_p_latex(float(row.p_holm))}$)"
            )
        if len(worst_test):
            row = worst_test.iloc[0]
            worst_records.append((dataset, float(row.mean_benefit)))
            worst_clauses.append(
                f"{dataset_name}: {format_pp(float(row.mean_benefit))} pp"
            )
        representation_test = dataset_tests[
            (dataset_tests.metric == "negative_transfer_rate_0p5")
            & (dataset_tests.reference.isin(["always_representation", "prequential_tent"]))
            & (dataset_tests.comparison_family == "routed_vs_baseline")
        ]
        if len(representation_test):
            row = representation_test.sort_values("p_holm").iloc[0]
            negative_transfer_outcomes.append(
                (float(row.mean_benefit), float(row.p_holm))
            )
            negative_transfer_records.append(
                (
                    dataset,
                    float(row.mean_benefit),
                    float(row.p_holm),
                    str(row.reference),
                )
            )
            negative_transfer_clauses.append(
                f"{dataset_name}: {float(row.mean_benefit) * 100:.2f} pp reduction "
                f"versus {latex_escape(str(row.reference).replace('_', ' '))} "
                f"(Holm $p={format_p_latex(float(row.p_holm))}$)"
            )
        if routed_method == "shiftroute_tent" and "prequential_tent" in set(
            run.loc[run.dataset == dataset, "method"].astype(str)
        ):
            tent_tests = dataset_tests[
                (dataset_tests.reference == "prequential_tent")
                & (dataset_tests.comparison_family == "routed_vs_baseline")
                & (dataset_tests.metric.isin(["mean_accuracy", "worst_window_accuracy"]))
            ]
            mean_rows = tent_tests[tent_tests.metric == "mean_accuracy"]
            worst_rows = tent_tests[tent_tests.metric == "worst_window_accuracy"]
            if len(mean_rows) and len(worst_rows):
                mean_row = mean_rows.iloc[0]
                worst_row = worst_rows.iloc[0]
                raw_tent_tradeoff_clauses.append(
                    f"{dataset_name}: mean {format_pp(float(mean_row.mean_benefit))} pp, "
                    f"worst window {format_pp(float(worst_row.mean_benefit))} pp"
                )
        diagnostic_group = diagnostic[diagnostic.dataset == dataset]
        if len(diagnostic_group):
            diagnostic_records.append(
                (
                    dataset,
                    float(diagnostic_group.prior_auroc.mean()),
                    float(diagnostic_group.representation_auroc.mean()),
                )
            )
            diagnostic_clauses.append(
                f"{dataset_name}: prior AUROC {diagnostic_group.prior_auroc.mean():.3f}, "
                f"representation AUROC {diagnostic_group.representation_auroc.mean():.3f}"
            )
        route_group = route[route.dataset == dataset]
        if len(route_group):
            routing_records.append(
                (
                    dataset,
                    float(route_group.steady_action_accuracy.mean()),
                    float(route_group.clean_steady_false_action_rate.mean()),
                )
            )
            routing_clauses.append(
                f"{dataset_name}: all-window/steady action accuracy "
                f"{format_probability(route_group.action_accuracy.mean())}/"
                f"{format_probability(route_group.steady_action_accuracy.mean())}, "
                f"clean false action {format_probability(route_group.clean_false_action_rate.mean())}/"
                f"{format_probability(route_group.clean_steady_false_action_rate.mean())}"
            )

    calibration_clauses = []
    calibration_records: list[tuple[str, int, int, float]] = []
    for dataset in datasets:
        rows = calibration[
            (calibration.dataset == dataset)
            & (calibration.measure == "diagnostic_familywise_alarm")
        ]
        if len(rows):
            row = rows.iloc[0]
            calibration_records.append(
                (dataset, int(row.alarms), int(row.clean_windows), float(row.rate))
            )
            calibration_clauses.append(
                f"{latex_escape(dataset)}: {int(row.alarms)}/{int(row.clean_windows)} "
                f"({format_probability(float(row.rate))})"
            )

    audit_clauses = []
    audit_inputs: list[Path] = []
    if args.calibration_audit_root is not None and args.calibration_audit_root.exists():
        for summary_path in sorted(args.calibration_audit_root.glob("*/summary.json")):
            audit = json.loads(summary_path.read_text(encoding="utf-8"))
            audit_inputs.append(summary_path)
            audit_name = summary_path.parent.name.replace("_resnet18", "")
            pretty_audit_names = {
                "cifar10": "CIFAR10-C",
                "cifar100": "CIFAR100-C",
                "imagenet100_resnet50_w128": "ImageNet100 (window 128)",
                "imagenet100_resnet50_w256": "ImageNet100 (window 256)",
                "imagenet100_resnet50_w512": "ImageNet100 (window 512)",
            }
            name = latex_escape(pretty_audit_names.get(audit_name, audit_name))
            audit_clauses.append(
                f"{name}: primary {audit['primary_alarms']}/"
                f"{audit['primary_identity_disjoint_windows']}, grouping-sensitivity range "
                f"{float(audit['partition_sensitivity_rate_min']) * 100:.2f}--"
                f"{float(audit['partition_sensitivity_rate_max']) * 100:.2f}\\%"
            )

    cluster_path = args.cluster_aware_primary or (
        args.output.parent / "cluster_aware_primary_comparisons.csv"
    )
    if not cluster_path.exists():
        raise FileNotFoundError(
            "cluster-aware primary comparisons are required; run "
            "scripts/cluster_aware_inference.py first"
        )
    cluster_primary = pd.read_csv(cluster_path)
    inferential = cluster_primary[cluster_primary.analysis_status == "inferential"].copy()
    mean_primary = inferential[inferential.metric == "mean_accuracy"]
    nt_primary = inferential[inferential.metric == "negative_transfer_rate_0p5"]
    source_outcomes = [
        (float(row.mean_benefit), float(row.holm_p_existing_family))
        for row in mean_primary.itertuples(index=False)
    ]
    mean_records = [
        (str(row.dataset), float(row.mean_benefit), float(row.holm_p_existing_family))
        for row in mean_primary.itertuples(index=False)
    ]
    negative_transfer_outcomes = [
        (float(row.mean_benefit), float(row.holm_p_existing_family))
        for row in nt_primary.itertuples(index=False)
    ]
    negative_transfer_records = [
        (
            str(row.dataset),
            float(row.mean_benefit),
            float(row.holm_p_existing_family),
            str(row.reference),
        )
        for row in nt_primary.itertuples(index=False)
    ]

    improved = sum(benefit > 0.0 and p_value < 0.05 for benefit, p_value in source_outcomes)
    decreased = sum(benefit < 0.0 and p_value < 0.05 for benefit, p_value in source_outcomes)
    tied = len(source_outcomes) - improved - decreased
    significant_nt = [
        benefit for benefit, p_value in negative_transfer_outcomes
        if benefit > 0.0 and p_value < 0.05
    ]
    source_summary = (
        f"ShiftRoute significantly improved mean accuracy over the frozen source in "
        f"{improved}/{len(source_outcomes)} evaluation suites and was not significantly "
        f"different in {tied}/{len(source_outcomes)}"
    )
    if decreased:
        source_summary += f", with significant decreases in {decreased}/{len(source_outcomes)}"
    else:
        source_summary += ", with no significant decrease"
    if significant_nt:
        nt_summary = (
            f"the rate of losses exceeding 0.5 percentage points was significantly "
            f"reduced versus the prespecified fixed representation/Tent comparison in "
            f"{len(significant_nt)}/{len(negative_transfer_outcomes)} suites "
            f"(observed reductions {min(significant_nt) * 100:.2f}--"
            f"{max(significant_nt) * 100:.2f} pp)"
        )
    else:
        nt_summary = "no significant negative-transfer reduction was established"
    main_sentence = (
        "ShiftRoute's primary result concerns damaging adaptation: "
        + nt_summary
        + f". Mean accuracy was a secondary, mixed outcome: significant gains in "
        f"{improved}/{len(source_outcomes)} suites, no significant difference in "
        f"{tied}/{len(source_outcomes)}, and significant decreases in "
        f"{decreased}/{len(source_outcomes)}."
    )
    family_count = len({dataset_family(dataset) for dataset in datasets})

    # Keep the manuscript prose compact.  The complete per-suite values remain
    # in generated tables; these summaries expose the strongest and adverse
    # outcomes without duplicating eleven table rows as one long paragraph.
    significant_gains = [row for row in mean_records if row[1] > 0 and row[2] < 0.05]
    significant_losses = [row for row in mean_records if row[1] < 0 and row[2] < 0.05]

    def format_effects(records: list[tuple[str, float, float]]) -> str:
        return ", ".join(
            f"{latex_escape(name)} ({format_pp(effect)} pp)"
            for name, effect, _ in records
        )

    gain_text = (
        f"significant gains occurred in {format_effects(significant_gains)}"
        if significant_gains
        else "no significant gain occurred"
    )
    loss_text = (
        f"significant decreases occurred in {format_effects(significant_losses)}"
        if significant_losses
        else "no significant decrease occurred"
    )
    mean_summary = (
        f"Against the frozen source, {gain_text}, while {loss_text}; the remaining "
        f"{tied}/{len(mean_records)} inferential suites were not significantly "
        f"different after Holm correction. ImageNet100 and ImageNetV2 are descriptive."
    )

    worst_low = min(worst_records, key=lambda row: row[1])
    worst_high = max(worst_records, key=lambda row: row[1])
    worst_summary = (
        f"Worst-window changes versus the frozen source ranged from "
        f"{format_pp(worst_low[1])} pp on {latex_escape(worst_low[0])} to "
        f"{format_pp(worst_high[1])} pp on {latex_escape(worst_high[0])}."
    )

    significant_nt_records = [
        row for row in negative_transfer_records if row[1] > 0 and row[2] < 0.05
    ]
    largest_nt = sorted(significant_nt_records, key=lambda row: row[1], reverse=True)[:2]
    largest_nt_text = ", ".join(
        f"{latex_escape(name)} ({effect * 100:.2f} pp)"
        for name, effect, _, _ in largest_nt
    )
    negative_transfer_summary = (
        f"Significant reductions occurred in {len(significant_nt_records)}/"
        f"{len(negative_transfer_records)} suites, with the largest on "
        f"{largest_nt_text}; complete effects and adjusted $p$-values are retained in the reproducibility bundle."
    )

    prior_low = min(diagnostic_records, key=lambda row: row[1])
    prior_high = max(diagnostic_records, key=lambda row: row[1])
    representation_low = min(diagnostic_records, key=lambda row: row[2])
    representation_high = max(diagnostic_records, key=lambda row: row[2])
    diagnostic_summary = (
        f"Mean prior-shift AUROC ranged from {prior_low[1]:.3f} "
        f"({latex_escape(prior_low[0])}) to {prior_high[1]:.3f} "
        f"({latex_escape(prior_high[0])}); representation-shift AUROC ranged "
        f"from {representation_low[2]:.3f} ({latex_escape(representation_low[0])}) "
        f"to {representation_high[2]:.3f} ({latex_escape(representation_high[0])})."
    )

    route_low = min(routing_records, key=lambda row: row[1])
    route_high = max(routing_records, key=lambda row: row[1])
    zero_clean_routes = sum(rate == 0.0 for _, _, rate in routing_records)
    route_summary = (
        f"Steady-window action accuracy ranged from {format_probability(route_low[1])} "
        f"({latex_escape(route_low[0])}) to {format_probability(route_high[1])} "
        f"({latex_escape(route_high[0])}); {zero_clean_routes}/{len(routing_records)} "
        f"suites had zero steady-window clean false actions."
    )

    calibration_low = min(calibration_records, key=lambda row: row[3])
    calibration_high = max(calibration_records, key=lambda row: row[3])
    calibration_summary = (
        f"Pooled clean diagnostic familywise alarm rates ranged from "
        f"{format_probability(calibration_low[3])} ({latex_escape(calibration_low[0])}) "
        f"to {format_probability(calibration_high[3])} "
        f"({latex_escape(calibration_high[0])})."
    )
    lines = [
        "% Generated only from hashed aggregate artifacts. Do not edit numerical claims manually.",
        f"\\newcommand{{\\DatasetCount}}{{{family_count}}}",
        f"\\newcommand{{\\ConditionCount}}{{{condition_count}}}",
        f"\\newcommand{{\\BackboneCount}}{{{args.backbone_count}}}",
        f"\\newcommand{{\\MainResultSentence}}{{{main_sentence}}}",
        f"\\newcommand{{\\MeanAccuracyResult}}{{{mean_summary}}}",
        f"\\newcommand{{\\WorstWindowResult}}{{{worst_summary}}}",
        f"\\newcommand{{\\NegativeTransferResult}}{{{negative_transfer_summary}}}",
        f"\\newcommand{{\\RawTentTradeoffResult}}{{{join_clauses(raw_tent_tradeoff_clauses)}}}",
        f"\\newcommand{{\\DiagnosticResult}}{{{diagnostic_summary}}}",
        f"\\newcommand{{\\RoutingResult}}{{{route_summary}}}",
        f"\\newcommand{{\\CalibrationResult}}{{{calibration_summary}}}",
        f"\\newcommand{{\\CalibrationAuditResult}}{{{join_clauses(audit_clauses)}}}",
    ]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    manifest = {
        "aggregate_dir": str(args.aggregate_dir),
        "datasets": datasets,
        "dataset_families": sorted({dataset_family(dataset) for dataset in datasets}),
        "condition_cells": condition_count,
        "backbone_count": args.backbone_count,
        "inputs": [
            {"path": str(path), "sha256": sha256(path)}
            for path in list(paths.values()) + audit_inputs + [cluster_path]
        ],
        "output": {"path": str(args.output), "sha256": sha256(args.output)},
    }
    manifest_path = args.output.with_suffix(".manifest.json")
    manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    print(json.dumps(manifest), flush=True)


if __name__ == "__main__":
    main()
